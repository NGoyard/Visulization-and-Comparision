    def h(u, v):
        ux, uy = G.nodes[u]['x'], G.nodes[u]['y']
        vx, vy = G.nodes[v]['x'], G.nodes[v]['y']
        return sqrt((ux - vx)**2 + (uy - vy)**2)
    visited = set()
    heap = [(h(start, goal), start, [start])]
