def generate_random_coordinates(center, radius_km, n):
    coordinates = []
    lat_center, lon_center = center
    for _ in range(n):
        angle = random.uniform(0, 2 * math.pi)
        radius = random.uniform(0, radius_km)

        delta_lat = (radius / 111) * math.cos(angle)
