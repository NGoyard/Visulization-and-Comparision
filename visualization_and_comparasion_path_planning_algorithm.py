def best_first_search(graph, start, goal):
    import heapq
    def heuristic(u, v):
        ux, uy = graph.nodes[u]['x'], graph.nodes[u]['y']
        vx, vy = graph.nodes[v]['x'], graph.nodes[v]['y']
        return sqrt((ux - vx)**2 + (uy - vy)**2)
    visited = set()
    heap = [(heuristic(start, goal), start, [start])]
    while heap:
        _, current, path = heapq.heappop(heap)
        if current == goal:
            return path
        if current in visited:
            continue
        visited.add(current)
        for neighbor in graph.neighbors(current):
            if neighbor not in visited:
                heapq.heappush(heap, (heuristic(neighbor, goal), neighbor, path + [neighbor]))
    return None

def dfs_path(graph, start, goal):
    stack = [(start, [start])]
    visited = set()
    while stack:
        vertex, path = stack.pop()
        if vertex == goal:
            return path
        if vertex in visited:
            continue
        visited.add(vertex)
        for neighbor in graph.neighbors(vertex):
            if neighbor not in visited:
                stack.append((neighbor, path + [neighbor]))
    return None

def bfs_path(graph, start, goal):
    from collections import deque
    queue = deque([(start, [start])])
    visited = set([start])
    while queue:
        vertex, path = queue.popleft()
        if vertex == goal:
            return path
        for neighbor in graph.neighbors(vertex):
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, path + [neighbor]))
    return None

def jps_path(graph, start, goal):
    try:
        return nx.astar_path(graph, start, goal, weight='length')
    except nx.NetworkXNoPath:
        return None

